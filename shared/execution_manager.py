"""
Execution State Manager — manages the lifecycle of an execution plan.

Responsibilities:
- Stores and manages the ExecutionPlan
- Executes tasks sequentially via the agent's tool system
- Emits structured events for frontend streaming
- Handles dynamic plan modifications (add/insert tasks)
- Integrates with existing Agent and ToolRegistry
"""

from __future__ import annotations

import json
import logging
import time
import uuid
from dataclasses import dataclass
from typing import Any, Callable

from shared.execution_plan import (
    ExecutionPlan,
    ExecutionEvent,
    EventType,
    TaskStatus,
    Task,
    EXECUTION_PLAN_JSON_SCHEMA,
)

logger = logging.getLogger("execution_manager")


@dataclass
class ExecutionContext:
    """Context passed to task execution functions."""
    user_input: str
    plan: ExecutionPlan
    agent: Any  # The Agent instance
    event_sink: Callable[[ExecutionEvent], None]
    tool_registry: Any
    llm_client: Any


class ExecutionManager:
    """
    Manages execution of an ExecutionPlan sequentially.
    
    The manager:
    1. Receives a plan (generated by LLM or predefined)
    2. Executes tasks one by one, updating status
    3. Emits events for each state change
    4. Supports dynamic plan modification during execution
    5. Handles tool calls within tasks
    """
    
    def __init__(
        self,
        plan: ExecutionPlan,
        agent: Any,
        event_sink: Callable[[ExecutionEvent], None],
        tool_registry: Any,
        llm_client: Any,
        user_input: str,
    ):
        self.plan = plan
        self.agent = agent
        self.event_sink = event_sink
        self.tool_registry = tool_registry
        self.llm_client = llm_client
        self.user_input = user_input
        
        # Internal state
        self._running = False
        self._current_task: Task | None = None
        self._context: ExecutionContext | None = None
        
    def _emit(self, event: ExecutionEvent):
        """Emit event through the sink."""
        try:
            self.event_sink(event)
        except Exception as e:
            logger.error(f"[ExecutionManager] Failed to emit event: {e}")

    def _emit_plan_created(self):
        self._emit(ExecutionEvent.plan_created(self.plan))

    def _emit_plan_updated(self):
        self._emit(ExecutionEvent.plan_updated(self.plan))

    def _emit_task_started(self, task: Task):
        self._emit(ExecutionEvent.task_started(self.plan, task))

    def _emit_task_completed(self, task: Task):
        self._emit(ExecutionEvent.task_completed(self.plan, task))

    def _emit_task_failed(self, task: Task, error: str):
        self._emit(ExecutionEvent.task_failed(self.plan, task, error))

    def _emit_tool_started(self, task_id: str, tool_name: str, tool_args: dict):
        self._emit(ExecutionEvent.tool_started(self.plan, task_id, tool_name, tool_args))

    def _emit_tool_completed(self, task_id: str, tool_name: str, tool_result: dict):
        self._emit(ExecutionEvent.tool_completed(self.plan, task_id, tool_name, tool_result))

    def _emit_execution_error(self, error: str, task_id: str | None = None):
        self._emit(ExecutionEvent.execution_error(self.plan, error, task_id))

    def _emit_execution_completed(self, final_message: str):
        self._emit(ExecutionEvent.execution_completed(self.plan, final_message))

    def _emit_agent_message(self, message: str):
        self._emit(ExecutionEvent.agent_message(message))

    # -------------------------------------------------------------------------
    # Public API
    # -------------------------------------------------------------------------

    def execute(self) -> ExecutionPlan:
        """
        Execute all tasks in the plan sequentially.
        Returns the final plan with all task statuses updated.
        """
        self._running = True
        self._emit_plan_created()
        
        try:
            # Execute each task
            while self.plan.current_task_index < len(self.plan.tasks):
                task = self.plan.tasks[self.plan.current_task_index]
                if task.status != TaskStatus.PENDING:
                    self.plan.current_task_index += 1
                    continue
                
                self._current_task = task
                self._execute_task(task)
                
                if not self._running:
                    break
                    
        except Exception as e:
            logger.exception("[ExecutionManager] Fatal error during execution")
            self._emit_execution_error(f"Execution failed: {e}")
        finally:
            self._running = False
            
        return self.plan

    def _execute_task(self, task: Task):
        """Execute a single task."""
        logger.info(f"[ExecutionManager] Starting task: {task.title}")
        
        # Update task status to in_progress
        self.plan.update_task_status(task.id, TaskStatus.IN_PROGRESS)
        self._emit_task_started(task)
        
        # Build a prompt for the LLM to execute this specific task
        # The LLM should use tools to accomplish the task
        task_prompt = self._build_task_prompt(task)
        
        try:
            # Use the agent's existing LLM and tool system
            # We run a focused iteration for this task
            result = self._run_task_iteration(task, task_prompt)
            
            if result.get("error"):
                self.plan.update_task_status(task.id, TaskStatus.FAILED, result["error"])
                self._emit_task_failed(task, result["error"])
                self._emit_execution_error(result["error"], task.id)
            else:
                self.plan.update_task_status(task.id, TaskStatus.COMPLETED)
                self._emit_task_completed(task)
                
        except Exception as e:
            logger.exception(f"[ExecutionManager] Task {task.id} failed with exception")
            self.plan.update_task_status(task.id, TaskStatus.FAILED, str(e))
            self._emit_task_failed(task, str(e))
            self._emit_execution_error(str(e), task.id)

    def _build_task_prompt(self, task: Task) -> str:
        """Build a focused prompt for executing a specific task."""
        return (
            f"Выполните следующую задачу из плана:\n\n"
            f"Задача: {task.title}\n"
            f"Описание: {task.description}\n\n"
            f"Исходный запрос пользователя: {self.user_input}\n\n"
            f"Используйте доступные инструменты для выполнения этой задачи. "
            f"Когда задача будет выполнена, дайте краткий отчёт о результате."
        )

    def _run_task_iteration(self, task: Task, task_prompt: str) -> dict:
        """
        Run a single LLM iteration to execute the task.
        This leverages the existing agent LLM and tool calling infrastructure.
        """
        # Build messages for the LLM
        messages = [
            {"role": "system", "content": self.agent.system_prompt},
            {"role": "user", "content": task_prompt}
        ]
        
        # Get available tools
        tools = self.agent._build_tools_for_llm()
        
        # Ask LLM
        max_tokens = min(2000, self.agent.context.calc_max_tokens())
        content, tool_calls, finish_reason = self.llm_client.ask(
            messages=messages,
            tools=tools,
            max_tokens=max_tokens,
            temperature=0.1,
        )
        
        # Handle tool calls
        if tool_calls:
            tc_list = [
                {
                    "id": tc.id,
                    "type": "function",
                    "function": {
                        "name": tc.function.name,
                        "arguments": tc.function.arguments,
                    },
                }
                for tc in tool_calls
            ]
            
            # Execute each tool call
            for tc_info in tc_list:
                tool_name = tc_info["function"]["name"]
                try:
                    tool_args = json.loads(tc_info["function"]["arguments"])
                except json.JSONDecodeError:
                    tool_args = {}
                
                # Emit tool started
                self.plan.record_tool_call(task.id, tool_name)
                self._emit_tool_started(task.id, tool_name, tool_args)
                
                # Execute tool
                tool_result: Any = self.tool_registry.execute(tool_name, tool_args)
                
                # Emit tool completed
                result_dict = {
                    "status": tool_result.status,
                    "data": tool_result.data,
                    "error": tool_result.error,
                }
                self._emit_tool_completed(task.id, tool_name, result_dict)
                
                # Check if tool failed
                if tool_result.status != "success":
                    return {"error": f"Tool '{tool_name}' failed: {tool_result.error or tool_result.to_text()}"}
            
            # Task completed with tool calls, ask for summary
            followup_messages = messages + [
                {"role": "assistant", "content": content or "", "tool_calls": tc_list},
                {"role": "user", "content": "Задача выполнена. Дайте краткий отчёт о результате (1-2 предложения)."}
            ]
            
            summary_content, _, _ = self.llm_client.ask(
                messages=followup_messages,
                tools=None,
                max_tokens=200,
                temperature=0.1,
            )
            
            return {"output": summary_content}
        
        # No tool calls - just content response
        return {"output": content}

    # -------------------------------------------------------------------------
    # Dynamic Plan Modification
    # -------------------------------------------------------------------------

    def add_task(self, title: str, description: str = "", after_task_id: str | None = None) -> Task:
        """Add a new task to the plan dynamically."""
        if after_task_id:
            # Find index of after_task_id
            for i, t in enumerate(self.plan.tasks):
                if t.id == after_task_id:
                    new_task = self.plan.insert_task(i + 1, title, description)
                    self._emit_plan_updated()
                    return new_task
            # Not found, append
            new_task = self.plan.add_task(title, description)
        else:
            new_task = self.plan.add_task(title, description)
        
        self._emit_plan_updated()
        logger.info(f"[ExecutionManager] Added task dynamically: {title}")
        return new_task

    def update_task_status(self, task_id: str, status: TaskStatus, error: str | None = None) -> bool:
        """Update task status externally."""
        result = self.plan.update_task_status(task_id, status, error)
        if result:
            self._emit_plan_updated()
        return result

    def stop(self):
        """Stop execution gracefully."""
        self._running = False
        logger.info("[ExecutionManager] Execution stopped")


def create_execution_plan_from_llm(
    llm_client: Any,
    user_input: str,
    system_prompt: str,
    available_tools: list[dict],
) -> ExecutionPlan:
    """
    Generate an ExecutionPlan using LLM Structured Output.
    Uses the JSON schema to enforce structured response.
    """
    # Build the planning prompt
    planning_prompt = f"""Вы — инженер-планировщик. Пользователь дал задачу. Ваша работа — проанализировать запрос и создать план выполнения.

Запрос пользователя: {user_input}

Доступные инструменты:
{json.dumps([{"name": t["function"]["name"], "description": t["function"]["description"]} for t in available_tools], ensure_ascii=False, indent=2)}

Создайте план как последовательность конкретных, выполнимых задач. Каждая задача должна решаться с помощью доступных инструментов.
План должен логически вести от исследования к выполнению.

Верните план в JSON формате согласно схеме: {{"tasks": [{{"title": "...", "description": "..."}}], "reasoning": "..."}}."""

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": planning_prompt}
    ]
    
    # Try to use structured output if supported
    try:
        from shared.llm_client.providers import BaseProvider
        # Check if provider supports structured output
        provider_impl = getattr(llm_client, '_provider_impl', None)
        if provider_impl and hasattr(provider_impl, 'ask_structured'):
            schema = EXECUTION_PLAN_JSON_SCHEMA
            result = provider_impl.ask_structured(
                model=llm_client.model,
                messages=messages,
                schema=schema,
                max_tokens=1500,
                temperature=0.1,
            )
            if result and "tasks" in result:
                plan = ExecutionPlan(user_request=user_input)
                for t in result["tasks"]:
                    plan.add_task(t["title"], t.get("description", ""))
                return plan
    except Exception as e:
        logger.warning(f"[ExecutionManager] Structured output not available, falling back: {e}")
    
    # Fallback: regular completion with JSON parsing
    content, _, _ = llm_client.ask(
        messages=messages,
        tools=None,
        max_tokens=1500,
        temperature=0.1,
    )
    
    if content:
        try:
            # Try to extract JSON from response
            import re
            json_match = re.search(r'\{.*\}', content, re.DOTALL)
            if json_match:
                data = json.loads(json_match.group())
                if "tasks" in data:
                    plan = ExecutionPlan(user_request=user_input)
                    for t in data["tasks"]:
                        plan.add_task(t["title"], t.get("description", ""))
                    return plan
        except Exception as e:
            logger.warning(f"[ExecutionManager] Failed to parse plan JSON: {e}")
    
    raise RuntimeError(f"Failed to generate execution plan from LLM for request: '{user_input}'")